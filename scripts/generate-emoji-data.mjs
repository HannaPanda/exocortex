#!/usr/bin/env node
/**
 * Regenerates `apps/web/src/lib/emoji-data.generated.ts` from emojibase's German
 * dataset.
 *
 * German on purpose: the search field is German, so the labels and the keywords
 * it matches have to be. Skin-tone variants are dropped — they multiply the list
 * by five and a page icon is 16 pixels wide.
 *
 * About 160 kB, so it sits behind a dynamic `import()`. The picker shows the
 * small curated "Häufig" group from `emoji-catalog.ts` while it loads, which is
 * what almost every pick comes from anyway. The data is emitted as a
 * `JSON.parse` of one string literal for the reason spelled out in
 * `generate-icon-data.mjs`.
 *
 * Run after an emojibase upgrade: `pnpm data:generate`.
 */
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const emoji = require('emojibase-data/de/data.json');
const messages = require('emojibase-data/de/messages.json');

/** The "component" group holds skin-tone modifiers and hair colours, not emoji. */
const COMPONENT_GROUP = 2;

/** emojibase tags every entry with `all`; it matches everything and means nothing. */
const USELESS_TAGS = new Set(['all']);

const byGroup = new Map();
for (const entry of emoji) {
  if (typeof entry.group !== 'number' || entry.group === COMPONENT_GROUP) continue;
  const bucket = byGroup.get(entry.group) ?? [];
  bucket.push(entry);
  byGroup.set(entry.group, bucket);
}

const groups = [...messages.groups]
  .sort((a, b) => a.order - b.order)
  .flatMap((group) => {
    const entries = byGroup.get(group.order);
    if (entries === undefined) return [];
    entries.sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
    return [
      {
        key: group.key,
        label: group.message,
        // Tuples rather than objects: 1,900 entries × three key names is 60 kB of
        // repeated property names for nothing.
        emojis: entries.map((entry) => [
          entry.emoji,
          entry.label,
          (entry.tags ?? []).filter((tag) => !USELESS_TAGS.has(tag) && tag !== entry.label),
        ]),
      },
    ];
  });

const payload = JSON.stringify({ groups });
const file = `// Generated by scripts/generate-emoji-data.mjs. Do not edit by hand.
/* eslint-disable */
import type { EmojiData } from './emoji-catalog';

export const EMOJI_DATA = JSON.parse(
  '${payload.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',
) as EmojiData;
`;
await writeFile(path.join(repoRoot, 'apps/web/src/lib/emoji-data.generated.ts'), file);

const count = groups.reduce((total, group) => total + group.emojis.length, 0);
console.log(`emoji: ${count} in ${groups.length} groups, ${(payload.length / 1024).toFixed(0)} kB`);
