#!/usr/bin/env node
/**
 * Regenerates `apps/web/src/lib/emoji-data/<locale>.generated.ts`, one file per
 * interface language, from emojibase's datasets (MIT; the names and keywords are
 * Unicode CLDR's annotations, Unicode License v3).
 *
 * One file per language on purpose: the search field speaks the reader's
 * language, so the labels and the keywords it matches have to as well, and a
 * reader only ever downloads their own. Every file also carries GitHub's
 * shortcodes (`tada`, `+1`, `thumbsup`) as keywords, because `:tada` is what
 * people type after a decade of chat programs, whatever their language.
 * Skin-tone variants are dropped: they multiply the list by five and a page
 * icon is 16 pixels wide.
 *
 * About 170 kB each, so they sit behind a dynamic `import()`. The picker shows
 * the small curated "Häufig" group from `emoji-catalog.ts` while one loads,
 * which is what almost every pick comes from anyway. The data is emitted as a
 * `JSON.parse` of one string literal for the reason spelled out in
 * `generate-icon-data.mjs`.
 *
 * Run after an emojibase upgrade, or when a locale is added: `pnpm data:generate`.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(repoRoot, 'apps/web/src/lib/emoji-data');

/**
 * Interface locale (`SUPPORTED_LOCALES` in `packages/contracts`) to emojibase
 * locale. `emoji-catalog.ts` imports one module per key and is typed against
 * `Locale`, so a locale added there without a file here fails the typecheck.
 */
const LOCALES = {
  de: 'de',
  en: 'en',
  es: 'es',
  fr: 'fr',
  it: 'it',
  nl: 'nl',
  pl: 'pl',
  'pt-BR': 'pt',
};

/** The "component" group holds skin-tone modifiers and hair colours, not emoji. */
const COMPONENT_GROUP = 2;

/** emojibase tags every entry with `all`; it matches everything and means nothing. */
const USELESS_TAGS = new Set(['all']);

/** hexcode -> GitHub shortcodes, the same for every language. */
const github = require('emojibase-data/en/shortcodes/github.json');

function shortcodesOf(hexcode) {
  const codes = github[hexcode];
  if (codes === undefined) return [];
  return Array.isArray(codes) ? codes : [codes];
}

function groupsFor(source) {
  const emoji = require(`emojibase-data/${source}/data.json`);
  const messages = require(`emojibase-data/${source}/messages.json`);

  const byGroup = new Map();
  for (const entry of emoji) {
    if (typeof entry.group !== 'number' || entry.group === COMPONENT_GROUP) continue;
    const bucket = byGroup.get(entry.group) ?? [];
    bucket.push(entry);
    byGroup.set(entry.group, bucket);
  }

  return [...messages.groups]
    .sort((a, b) => a.order - b.order)
    .flatMap((group) => {
      const entries = byGroup.get(group.order);
      if (entries === undefined) return [];
      entries.sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
      return [
        {
          key: group.key,
          label: group.message,
          // Tuples rather than objects: 1,900 entries × three key names is 60 kB of
          // repeated property names for nothing.
          emojis: entries.map((entry) => {
            const label = entry.label.toLowerCase();
            const keywords = [
              ...(entry.tags ?? []).map((tag) => tag.toLowerCase()),
              ...shortcodesOf(entry.hexcode),
            ].filter((tag) => !USELESS_TAGS.has(tag) && tag !== label);
            return [entry.emoji, entry.label, [...new Set(keywords)]];
          }),
        },
      ];
    });
}

await mkdir(outDir, { recursive: true });
for (const [locale, source] of Object.entries(LOCALES)) {
  const groups = groupsFor(source);
  const payload = JSON.stringify({ groups });
  const file = `// Generated by scripts/generate-emoji-data.mjs. Do not edit by hand.
/* eslint-disable */
import type { EmojiData } from '../emoji-catalog';

export const EMOJI_DATA = JSON.parse(
  '${payload.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',
) as EmojiData;
`;
  await writeFile(path.join(outDir, `${locale}.generated.ts`), file);
  const count = groups.reduce((total, group) => total + group.emojis.length, 0);
  console.log(
    `emoji ${locale}: ${count} in ${groups.length} groups, ${(payload.length / 1024).toFixed(0)} kB`,
  );
}
