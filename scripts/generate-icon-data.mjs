#!/usr/bin/env node
/**
 * Regenerates the two Lucide datasets the page icon picker needs.
 *
 *   packages/contracts/src/lucide-icon-names.ts
 *     Every canonical icon name, so `documentIconSchema` can validate an icon the
 *     picker or an MCP client picked. Names only: contracts must stay
 *     renderer-free.
 *
 *   apps/web/src/components/document/lucide-icon-nodes.generated.ts
 *     The path data of every icon plus Lucide's own aliases. Half a megabyte,
 *     which is why it is loaded through a dynamic `import()` and never part of
 *     the main bundle. `DocumentIcon` keeps a small static component map for the
 *     curated icons so the page tree paints without waiting for it.
 *
 *     The data is emitted as a `JSON.parse` of one string literal rather than as
 *     an object literal. Both are the same bytes on the wire, but an object
 *     literal would make TypeScript infer a type for all 1,756 entries and
 *     engines parse it as source; a string is one token to both.
 *
 * Run after a `lucide-react` upgrade: `pnpm data:generate`.
 */
import { createRequire } from 'node:module';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const lucideRoot = path.dirname(
  require.resolve('lucide-react/package.json', { paths: [path.join(repoRoot, 'apps/web')] }),
);
const iconsDir = path.join(lucideRoot, 'dist/esm/icons');

/**
 * Lucide ships one module per name, and an alias is a module that re-exports
 * another one's node. Reading the directory therefore yields canonical names and
 * aliases mixed together; `dynamicIconImports` is what tells them apart, because
 * its value is the *file* a name resolves to.
 */
const { default: dynamicIconImports } = await import(
  path.join(lucideRoot, 'dist/esm/dynamicIconImports.mjs')
);

const aliases = {};
for (const [name, load] of Object.entries(dynamicIconImports)) {
  const target = /icons\/([a-z0-9-]+)\.mjs/.exec(load.toString())?.[1];
  if (target !== undefined && target !== name) aliases[name] = target;
}

const nodes = {};
const files = (await readdir(iconsDir)).filter((file) => file.endsWith('.mjs')).sort();
for (const file of files) {
  const name = file.slice(0, -'.mjs'.length);
  if (name === 'index' || name in aliases) continue;
  const module = await import(path.join(iconsDir, file));
  if (module.__iconNode === undefined) continue;
  nodes[name] = module.__iconNode;
}

const names = Object.keys(nodes).sort();

const namesFile = `// Generated by scripts/generate-icon-data.mjs. Do not edit by hand.
/* eslint-disable */

/**
 * Every icon name Lucide draws, in Lucide's own kebab-case spelling.
 *
 * The list is the validation set behind \`documentIconSchema\`: a page icon is
 * stored as \`lucide:<name>\`, and a name that is not in here would leave the page
 * with a symbol that renders as nothing. It is *not* what the picker shows first
 * — that is the curated \`DOCUMENT_ICON_NAMES\` in \`primitives.ts\`.
 */
export const LUCIDE_ICON_NAMES: readonly string[] = [
${names.map((name) => `  '${name}',`).join('\n')}
];
`;

const payload = JSON.stringify({ nodes, aliases });
const nodesFile = `// Generated by scripts/generate-icon-data.mjs. Do not edit by hand.
/* eslint-disable */
import type { LucideIconData } from './lucide-icon-store';

export const LUCIDE_ICON_DATA = JSON.parse(${singleQuoted(payload)}) as LucideIconData;
`;

await mkdir(path.join(repoRoot, 'apps/web/src/components/document'), { recursive: true });
await writeFile(path.join(repoRoot, 'packages/contracts/src/lucide-icon-names.ts'), namesFile);
await writeFile(
  path.join(repoRoot, 'apps/web/src/components/document/lucide-icon-nodes.generated.ts'),
  nodesFile,
);

console.log(
  `lucide: ${names.length} icons, ${Object.keys(aliases).length} aliases, ` +
    `${(payload.length / 1024).toFixed(0)} kB of path data`,
);

/**
 * Wraps JSON in a single-quoted JS string. JSON uses double quotes throughout
 * and never contains a raw newline, so only a backslash or an apostrophe inside
 * the data could break out — neither occurs in path data today, and escaping
 * them keeps that from becoming a landmine later.
 */
function singleQuoted(text) {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}
